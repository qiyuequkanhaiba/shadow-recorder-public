import { strict as assert } from 'node:assert';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const TOKENS_PATH = join(__dirname, '../src-react/ui/tokens.css');
const OUTPUT_PATH = join(__dirname, '../src-electron/generated/overlay-theme.ts');
const SCREENSHOT_OVERLAY_PATH = join(__dirname, '../src-electron/screenshot-overlay-html.ts');

const ALLOWED_TOKENS = new Set([
  '--bg-canvas',
  '--bg-surface-1',
  '--bg-surface-2',
  '--bg-surface-3',
  '--bg-elevated',
  '--bg-overlay',
  '--bg-glass',
  '--text-primary',
  '--text-secondary',
  '--text-muted',
  '--text-on-glass',
  '--text-on-glass-secondary',
  '--text-on-glass-muted',
  '--border-on-glass',
  '--border-subtle',
  '--border-default',
  '--border-strong',
  '--accent-default',
  '--accent-hover',
  '--accent-active',
  '--accent-subtle',
  '--status-ok',
  '--status-ok-bg',
  '--status-ok-border',
  '--status-warn',
  '--status-warn-bg',
  '--status-warn-border',
  '--status-danger',
  '--status-danger-bg',
  '--status-danger-border',
  '--status-neutral',
  '--status-neutral-bg',
  '--status-neutral-border',
  '--shadow-sm',
  '--shadow-md',
  '--shadow-lg',
]);

const LITERAL_ANNOTATION_COLORS = [
  '#ff3b30',
  '#ffcc00',
  '#34c759',
  '#0a84ff',
  '#ffffff',
] as const;

function parseTokensBlock(css: string, selectorRegex: RegExp): Map<string, string> {
  const match = css.match(selectorRegex);
  const tokenMap = new Map<string, string>();
  if (!match || !match[1]) {
    return tokenMap;
  }
  const block = match[1];
  const varRegex = /(--[\w-]+)\s*:\s*([^;]+);/g;
  let varMatch: RegExpExecArray | null;
  while ((varMatch = varRegex.exec(block)) !== null) {
    const name = varMatch[1]?.trim();
    const value = varMatch[2]?.trim();
    if (name && value && ALLOWED_TOKENS.has(name)) {
      tokenMap.set(name, value);
    }
  }
  return tokenMap;
}

export function generateOverlayThemeContent(): string {
  const tokensCss = readFileSync(TOKENS_PATH, 'utf8');

  // Dark is defined in :root, :root[data-theme="dark"]
  const darkMap = parseTokensBlock(tokensCss, /(?::root\s*,\s*:root\[data-theme="dark"\]\s*\{)([^}]+)\}/);
  // Light is defined in :root[data-theme="light"]
  const lightMap = parseTokensBlock(tokensCss, /(?::root\[data-theme="light"\]\s*\{)([^}]+)\}/);

  const darkCssLines = Array.from(darkMap.entries())
    .map(([k, v]) => `    ${k}: ${v};`)
    .join('\n');

  const lightCssLines = Array.from(lightMap.entries())
    .map(([k, v]) => `    ${k}: ${v};`)
    .join('\n');

  return `// This file is auto-generated by scripts/generate-overlay-theme.ts
// Do not edit manually. Run "npm run generate:overlay-theme" to regenerate.

export const OVERLAY_THEME_DARK = \`
${darkCssLines}
\`;

export const OVERLAY_THEME_LIGHT = \`
${lightCssLines}
\`;

export const OVERLAY_THEME_CSS = \`
  :root, [data-theme="dark"] {
\${OVERLAY_THEME_DARK}
  }
  [data-theme="light"] {
\${OVERLAY_THEME_LIGHT}
  }
\`;

export const ANNOTATION_COLORS = ${JSON.stringify(LITERAL_ANNOTATION_COLORS, null, 2)} as const;
`;
}

function verifyScreenshotAnnotationColors(): void {
  const screenshotSource = readFileSync(SCREENSHOT_OVERLAY_PATH, 'utf8');
  for (const color of LITERAL_ANNOTATION_COLORS) {
    assert.ok(
      screenshotSource.includes(`data-color="${color}"`),
      `screenshot-overlay-html.ts must preserve literal annotation color: ${color}`,
    );
  }
}

function main(): void {
  const isCheckMode = process.argv.includes('--check');

  verifyScreenshotAnnotationColors();
  const nextContent = generateOverlayThemeContent();

  if (isCheckMode) {
    if (!existsSync(OUTPUT_PATH)) {
      console.error(`[check:overlay-theme] ERROR: ${OUTPUT_PATH} does not exist. Run "npm run generate:overlay-theme"`);
      process.exit(1);
    }
    const currentContent = readFileSync(OUTPUT_PATH, 'utf8');
    if (currentContent !== nextContent) {
      console.error(`[check:overlay-theme] ERROR: ${OUTPUT_PATH} is out of date. Run "npm run generate:overlay-theme"`);
      process.exit(1);
    }
    console.log('[check:overlay-theme] PASS');
    process.exit(0);
  } else {
    const targetDir = dirname(OUTPUT_PATH);
    if (!existsSync(targetDir)) {
      mkdirSync(targetDir, { recursive: true });
    }
    writeFileSync(OUTPUT_PATH, nextContent, 'utf8');
    console.log(`[generate:overlay-theme] Generated ${OUTPUT_PATH}`);
    process.exit(0);
  }
}

main();
